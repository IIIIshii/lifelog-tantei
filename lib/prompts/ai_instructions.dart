// Geminiへ渡すシステム指示・隠し指示を一元管理するファイル。
// キャラクター（人格・固定質問）の定義は lib/roles/ に移管済み。
// ここはロール非依存の指示（日記生成・解析・フォローアップの定型部）を扱う。
class AiInstructions {
  AiInstructions._();

  // ── AIフォローアップ質問時の隠し指示 ─────────────────────────
  // generateFollowUp 呼び出し時にプロンプトへ追加する。UI には表示しない。
  // モデルには responseSchema により {sufficient, question} のJSONを返させる。
  //
  // interviewerInstruction には選択中ロールの人格指示（Role.interviewerInstruction）を渡す。
  // 人格は呼び出し側モデルの systemInstruction にも入っているため、ここでの注入は1回に留める。
  static String followUpHint(String interviewerInstruction) {
    return '$interviewerInstruction\n'
        'この人格のまま、この証言を読み、まだ見えていない場面・背景・感情の余白を一つ選んで質問してください。\n'
        'トピックをチェックリスト的に埋めるのではなく、話の流れから自然に浮かび上がる\n'
        '「その場の空気感」や「そのとき何を感じていたか」を掘り下げるような問いかけにしてください。\n'
        '探偵らしく短く、しかし的を射た質問を一つだけ投げてください。\n'
        '\n'
        '出力は次のJSON形式に従ってください：\n'
        '- 証言が十分に語られていると判断した場合: {"sufficient": true, "question": ""}\n'
        '- まだ深掘りすべきと判断した場合: {"sufficient": false, "question": "次の質問文"}\n'
        'question 以外の余計な文章や前置きは出力しないでください。';
  }

  // ── 自由記述へのリアクション時の隠し指示 ─────────────────────
  // generateReaction 呼び出し時にプロンプトへ追加する。質問ではなく、直近の証言への
  // 短い相槌・気づきを1文だけ返させる（次の固定質問は別途投げられるため問いかけない）。
  //
  // interviewerInstruction には選択中ロールの人格指示（Role.interviewerInstruction）を渡す。
  // 人格は呼び出し側モデルの systemInstruction にも入っているため、ここでの注入は1回に留める。
  static String reactionHint(String interviewerInstruction) {
    return '$interviewerInstruction\n'
        'この人格のまま、直前の依頼人の証言に対して短い相槌・気づきのコメントを返してください。\n'
        '【厳守】\n'
        '- 質問はしないこと。問いかけや「？」で終わらせない（次の質問は別途投げられる）。\n'
        '- 1文だけ、簡潔に。前置き・見出し・引用符・依頼人の発言の繰り返しは不要。\n'
        '- ネガティブな言葉・評価は一切使わないこと。\n'
        '- 本文（コメント文）のみを出力すること。';
  }

  // ── 日記生成モデルのシステム指示 ─────────────────────────────
  // 日記生成専用 GenerativeModel の systemInstruction として事前にセットする。
  // 文体・視点（口調・人称・記録の形式）は選択中ロールの Role.diaryStyle を差し込み、
  // ここでは字数・ネガティブ禁止・本文のみといったロール非依存の不変ルールだけを規定する。
  // 三人称は強制しない（ロールにより一人称・二人称もあり得る）。
  static String diaryWriter(String diaryStyle) {
    return '上記の証言をもとに、次の文体で今日の記録を100〜300字で生成してください。\n\n'
        '【文体・視点】\n'
        '$diaryStyle\n\n'
        '【ルール】\n'
        '- 指定された文体・視点を保って記述する\n'
        '- ネガティブな表現・評価は一切含めない\n'
        '- 証言にある事実をもとに記録する（事実にない事柄を創作しない）\n'
        '- 日付や「捜査番号」などの見出しは不要。本文のみ出力する';
  }

  // ── 解析モデルのシステム指示 ─────────────────────────────────
  // 直近14日分の事件簿（日記＋回答）を読み返し、所見を記す役。
  // 文体は選択中ロールの Role.analystStyle を差し込み、役割とルールはここに集約する。
  static String analyst(String analystStyle) {
    return 'あなたは過去の事件簿群を読み返し、傾向と兆候を所見として記す役です。\n'
        '依頼人の直近の記録（日記と回答）を俯瞰し、繰り返されているパターン・気になる兆候・'
        '取り組みの中で光っている点を、次の文体で簡潔に記録してください。\n\n'
        '【文体・視点】\n'
        '$analystStyle\n\n'
        '【ルール】\n'
        '- 指定された文体・視点を保って記述する\n'
        '- ネガティブな断定や評価（怠けている、ダメ、など）は使わない\n'
        '- データから読み取れない事柄を断定しない（推測は推測として記す）\n'
        '- 数字や固有名詞は記録から拾って具体的に書く';
  }

  // ── 自己申告プロフィールの差し込みブロック ─────────────────
  // ユーザーが自己分析ページで登録した情報（MBTI等）を systemInstruction の末尾に足す。
  // body には SelfAnalysis.promptSummary() の結果を渡す。空なら空文字を返し、
  // 呼び出し側でセクションごと真略できるようにする（DiaryPrompts の additionalContext と同じ流儀）。
  //
  // 注入は systemInstruction の1回だけに留める（ロール人格と同じ方針）。
  // 「決めつけさせない」ための注意書きをここに集約しているのは、
  // 性格タイプには当たり外れがあり、AIが断定するとユーザーの体験を損なうため。
  static String selfProfile(String body) {
    if (body.isEmpty) return '';
    return '\n\n【依頼人の自己申告プロフィール】\n'
        '$body\n'
        '【扱い方】\n'
        '- これは依頼人本人が登録した自己申告であり、断定の材料ではない\n'
        '- 「あなたは〜な人だから」のようなレッテル貼り・決めつけはしないこと\n'
        '- プロフィール自体に言及する必要はない。質問の切り口や語り口を選ぶ参考に留めること\n'
        '- 記録された事実と食い違う場合は、常に事実の方を優先すること';
  }

  // ── 相談室（目標の壁打ち）時の隠し指示 ─────────────────────
  // consultGoal 呼び出し時にプロンプトへ追加する。UI には表示しない。
  // モデルには responseSchema により {ready, reply, title, ...} のJSONを返させる。
  //
  // interviewerInstruction には選択中ロールの人格指示（Role.interviewerInstruction）を渡す。
  // 人格は呼び出し側モデルの systemInstruction にも入っているため、ここでの注入は1回に留める。
  static String goalCoachHint(String interviewerInstruction) {
    return '$interviewerInstruction\n'
        'この人格のまま、依頼人が持ち込んだ「こうなりたい」という願いを聞き、'
        '毎日追いかけられる形に絞り込むのがあなたの仕事です。\n'
        '\n'
        '【この対話のゴール】\n'
        'ふわりとした願いを、次の3点に分解すること。\n'
        '- 何がどうなったら達成なのか（数字で測れる形）\n'
        '- いつまでに\n'
        '- そのために毎日なにを記録するか\n'
        '3点が揃ったと判断したら ready を true にして見立てを提案してください。\n'
        '目安は3〜5往復です。\n'
        '\n'
        '【進め方】\n'
        '- 一度の発言で聞くことは1つだけ。質問を並べない\n'
        '- 依頼人が数字を出せないときは、こちらから候補を2〜3個示して選ばせる\n'
        '- 依頼人が言っていない数値・事情を勝手に決めつけない。必ず本人に確かめる\n'
        '- 健康・体重・食事の話題でも、医学的な助言や極端な数値目標は示さない\n'
        '\n'
        '【見立ての作り方】\n'
        '- title: 依頼人の言葉を活かした一文。数字を含める（例「3ヶ月で5kg減らす」）\n'
        '- metric: 何がどうなったら達成なのか。基準は1つに絞る\n'
        '- deadline: YYYY-MM-DD 形式。決められなければ空文字\n'
        '- actions: 毎日の記録で追う項目。件数は【記録枠】の指示に従う（多いほど続かなくなる）\n'
        '  - type は numeric（数字を記録する）か check（やったかどうかを記録する）\n'
        '  - numeric には unit（kg・歩・分など）を必ず付ける。check の unit は空文字\n'
        '  - 1日1回、1タップか1つの数字で答えられる粒度にする\n'
        '    （「週3回ジムに行く」なら check の「ジムに行く」にする）\n'
        '- questions: 日々の記録で本人に投げかける質問を3〜5問。\n'
        '  数字では拾えない手応え・気分・つまずきを聞くものにする（actions とは別物）\n'
        '\n'
        '【厳守】\n'
        '- ネガティブな言葉・評価・説教は一切しない\n'
        '- reply は探偵の発言そのもの。見出し・箇条書き・JSONの説明は書かない\n'
        '- ready が false のときは title・actions・questions を空のままにする';
  }

  // 「これで目標にする」を押されたときに足す指示。
  // 依頼人が待たされ続けないよう、材料が足りなくてもその時点の最良案を出させる。
  static String goalForceProposeHint() {
    return '\n\n【追加の指示】\n'
        '依頼人は今すぐ見立てを立てることを望んでいます。'
        '材料が足りなくても、ここまでの話から組める最良の案で ready を true にしてください。'
        '足りない部分は無難な既定値で埋め、後から見直せることを reply で一言添えてください。';
  }

  // 毎日の記録に加えられる行動項目の残り枠を伝える指示。goalCoachHint の後ろに足す。
  //
  // 「全目標を合わせて kMaxTotalGoalActions 件まで」という制約は AI からは見えない。
  // その時点の残り枠を毎回数字で渡し、採用できない件数の案を出させないようにする。
  static String goalActionBudgetHint(int remaining) {
    if (remaining <= 0) {
      return '\n\n【記録枠】\n'
          '毎日の記録に加えられる項目はもう残っていません。'
          'actions は空配列にし、今ある記録項目の範囲で追える形に落としてください。'
          '記録項目を増やせないことは reply で一言添えてください。';
    }
    return '\n\n【記録枠】\n'
        '毎日の記録に加えられる項目は残り$remaining件です。'
        'actions は$remaining件以内にしてください。';
  }
}
